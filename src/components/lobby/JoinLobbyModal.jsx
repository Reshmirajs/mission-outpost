import { useState } from 'react'

/**
 * JoinLobbyModal Component
 * Collects 6-character room code and astronaut callsign to join an existing outpost mission.
 */
export default function JoinLobbyModal({
  onJoinLobby,
  onBack,
  onClose,
  isLoading = false,
  errorMessage = '',
}) {
  const [roomCode, setRoomCode] = useState('')
  const [callsign, setCallsign] = useState('')
  const [validationError, setValidationError] = useState('')

  const handleCodeChange = (e) => {
    const cleaned = e.target.value.toUpperCase().replace(/[^A-Z0-9]/g, '').slice(0, 6)
    setRoomCode(cleaned)
    if (validationError) setValidationError('')
  }

  const handleSubmit = (e) => {
    e.preventDefault()
    const cleanCode = roomCode.trim().toUpperCase()
    const cleanName = callsign.trim()

    if (!cleanCode) {
      setValidationError('Please enter a 6-character outpost access code.')
      return
    }
    if (cleanCode.length !== 6) {
      setValidationError(`Outpost access codes must be exactly 6 characters. (${cleanCode.length}/6 entered)`)
      return
    }
    if (!cleanName) {
      setValidationError('Please enter your astronaut callsign or name.')
      return
    }
    if (cleanName.length < 2) {
      setValidationError('Callsign must be at least 2 characters.')
      return
    }
    if (cleanName.length > 20) {
      setValidationError('Callsign must be 20 characters or fewer.')
      return
    }

    setValidationError('')
    onJoinLobby(cleanCode, cleanName)
  }

  return (
    <div className="lobby-modal-backdrop" role="dialog" aria-modal="true" aria-labelledby="join-lobby-title">
      <div className="lobby-form-modal-card">
        <button
          type="button"
          className="btn-modal-close"
          onClick={onClose}
          aria-label="Close modal"
        >
          ×
        </button>

        <div className="form-modal-header">
          <div className="form-header-badge">
            <span className="badge-icon">📡</span>
            <span>ASTRONAUT RENDEZVOUS</span>
          </div>
          <h2 id="join-lobby-title" className="form-modal-title">
            JOIN OUTPOST MISSION
          </h2>
          <p className="form-modal-subtitle">
            Enter the 6-character outpost access code provided by your Expedition Lead and your astronaut callsign.
          </p>
        </div>

        <form onSubmit={handleSubmit} className="lobby-form">
          <div className="form-group">
            <label htmlFor="join-code-input" className="form-label">
              6-Character Access Code
            </label>
            <input
              id="join-code-input"
              type="text"
              className="form-input code-input font-mono"
              placeholder="e.g. 7X9K2M"
              value={roomCode}
              onChange={handleCodeChange}
              maxLength={6}
              autoFocus
              disabled={isLoading}
            />
            <span className="input-hint">
              Case-insensitive uppercase code generated by the outpost creator.
            </span>
          </div>

          <div className="form-group">
            <label htmlFor="join-callsign-input" className="form-label">
              Your Astronaut Callsign / Name
            </label>
            <input
              id="join-callsign-input"
              type="text"
              className="form-input"
              placeholder="e.g. Specialist Alex, Cadet Maya..."
              value={callsign}
              onChange={(e) => {
                setCallsign(e.target.value)
                if (validationError) setValidationError('')
              }}
              maxLength={20}
              disabled={isLoading}
            />
            <span className="input-hint">
              This callsign will represent you in the squad assembly formation.
            </span>
          </div>

          {(validationError || errorMessage) && (
            <div className="form-error-callout" role="alert">
              ⚠️ {validationError || errorMessage}
            </div>
          )}

          <div className="form-modal-actions">
            <button
              type="button"
              className="btn-secondary"
              onClick={onBack}
              disabled={isLoading}
            >
              ← Back
            </button>
            <button
              type="submit"
              className="btn-primary"
              disabled={isLoading}
            >
              {isLoading ? 'Rendezvousing with Squad...' : 'Join Outpost Squad'}
            </button>
          </div>
        </form>
      </div>
    </div>
  )
}

